"""Verify citation-format normalisation (offline, no API key).

Background: on 2026-10-24 one report (gq-distillation) came back with ``[1][2]``
instead of ``[^1][^2]`` in the body. Because the reference list is generated by
code, citation existence still read 100% while the alignment judge sampled zero
claims — a silent metric blind spot. The normaliser makes format a code concern.

Run: python scripts/verify_citations.py
"""

from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "src"))

from deep_research.agents.nodes import _normalize_citations, _sanitize_citations  # noqa: E402
from deep_research.eval.judge import sample_cited_claims  # noqa: E402

REPORTS = pathlib.Path(__file__).resolve().parent.parent / "reports/eval/reports"


def test_basic_conversion() -> None:
    body = "结论一[1]，结论二[2][3]。"
    out, n = _normalize_citations(body, n_sources=3)
    assert out == "结论一[^1]，结论二[^2][^3]。", out
    assert n == 3
    print(f"[ok] 1. [n] → [^n]：{n} 处")


def test_idempotent_on_correct_format() -> None:
    body = "已经是脚注[^1]和[^2]。"
    out, n = _normalize_citations(body, n_sources=5)
    assert out == body and n == 0, (out, n)
    print("[ok] 2. 合规脚注不会被二次改写")


def test_out_of_range_untouched() -> None:
    body = "疑似编号[99]，有效引用[2]。"
    out, n = _normalize_citations(body, n_sources=5)
    assert "[99]" in out and "[^2]" in out and n == 1, out
    print("[ok] 3. 越界编号 [99] 不动（大概率不是引用），[2] 正常转换")


def test_code_regions_protected() -> None:
    body = "正文引用[1]。\n\n```python\narr[0] = 1\nrows[2] = 3\n```\n\n行内 `x[1]` 也不动。"
    out, n = _normalize_citations(body, n_sources=3)
    assert "arr[0] = 1" in out and "rows[2] = 3" in out, "代码块被改写"
    assert "`x[1]`" in out, "行内代码被改写"
    assert "正文引用[^1]" in out and n == 1, out
    print("[ok] 4. 代码块/行内代码原样保留，正文正常转换")


def test_markdown_links_protected() -> None:
    body = "见[1](https://example.com)链接，另见正文[2]。"
    out, n = _normalize_citations(body, n_sources=3)
    assert "[1](https://example.com)" in out, f"markdown 链接被破坏: {out}"
    assert "正文[^2]" in out and n == 1
    print("[ok] 5. Markdown 链接 [1](url) 不被误改")


def test_real_report_regression() -> None:
    """用真实出问题的报告：转换后应能抽到论断（原来抽到 0 条）。"""
    report = REPORTS / "gq-distillation.md"
    if not report.exists():
        print("[skip] 6. 没有 gq-distillation 报告可测")
        return
    text = report.read_text(encoding="utf-8")
    cut = text.find("## 参考")
    body = text[:cut] if cut > 0 else text
    before = len(sample_cited_claims(body))
    n_sources = len(re.findall(r"^\[\^\d+\]:", text, re.MULTILINE)) or 25
    fixed, converted = _normalize_citations(body, n_sources)
    after = len(sample_cited_claims(fixed))
    print(
        f"[ok] 6. 真实报告回归：正文转换 {converted} 处，抽到论断 {before} → {after} 条"
    )
    assert after > 0, "归一化后仍然抽不到论断"


def main() -> None:
    test_basic_conversion()
    test_idempotent_on_correct_format()
    test_out_of_range_untouched()
    test_code_regions_protected()
    test_markdown_links_protected()
    test_real_report_regression()
    print("\nCITATION NORMALISATION TEST PASSED")


if __name__ == "__main__":
    main()
